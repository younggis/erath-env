function lerp(a: number, b: number, t: number): number { return a + (b - a) * t }

export function palette(name: string, t: number): number[] {
  const stops = STOPS[name] || STOPS.default
  const x = Math.max(0, Math.min(1, Number.isFinite(t) ? t : 0))
  for (let i = 0; i < stops.length - 1; i++) {
    const [p0, c0] = stops[i]
    const [p1, c1] = stops[i + 1]
    if (x >= p0 && x <= p1) {
      const f = (x - p0) / Math.max(1e-9, p1 - p0)
      return c0.map((v, k) => Math.round(lerp(v, c1[k], f)))
    }
  }
  return stops[stops.length - 1][1]
}

export function cssColor(name: string, t: number): string {
  const c = palette(name, t) as number[]
  return c.length === 4 ? `rgba(${c[0]},${c[1]},${c[2]},${c[3] / 255})` : `rgb(${c[0]},${c[1]},${c[2]})`
}

